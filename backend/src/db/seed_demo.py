# --- Step 3: occupancy (SPEC-7A FR-2, D6, D8) ------------------------------


async def _book_group(
    conn: AsyncConnection,
    showtime_id: int,
    free_rows: dict[str, list[int]],
    seat_ids: dict[tuple[str, int], int],
    guests: tuple[int, ...],
    rng: random.Random,
    now: datetime,
) -> int:
    """Hold and confirm one booking group on a showtime, in place.

    The group is one to four adjacent seats in a single row, held and confirmed
    through the reservation services so the same rules as a real booking apply.

    Args:
        conn: An open connection; the caller owns the transaction.
        showtime_id: The showtime to book on.
        free_rows: Free seat numbers per row label; the booked seats are
            removed, so the caller can keep filling the showtime.
        seat_ids: ``(row_label, seat_number)`` to seat id.
        guests: The guest account ids to choose the booker from.
        rng: The seeded generator, consumed for the group size, the run and the
            booker, in that order. Nothing is drawn when fewer than two seats
            are free, because the call returns immediately.
        now: The current instant passed to the services.

    Returns:
        int: How many seats were booked; ``0`` only when fewer than two seats are
        free, because D6 requires every showtime to keep at least one seat free,
        so a viewer never meets a sold-out showtime.
    """
    available = sum(len(numbers) for numbers in free_rows.values())
    if available <= 1:
        # D6's "never 100%": leave the last seat unbooked.
        return 0
    size = min(_pick_group_size(rng), available - 1)
    positions = _find_run(free_rows, size, rng)
    if positions is None:
        # The drawn size no longer fits in any row (the random fill fragments the
        # rows), so take the longest run that still does rather than stop here:
        # stopping early would leave the showtime below D6's band.
        for smaller in range(size - 1, 0, -1):
            positions = _find_run(free_rows, smaller, rng)
            if positions is not None:
                break
    if positions is None:
        return 0
    booker_id = guests[rng.randrange(len(guests))]
    reservation = await hold(
        conn,
        booker_id,
        showtime_id,
        [seat_ids[position] for position in positions],
        now,
    )
    await confirm(conn, booker_id, reservation.id, now)
    for row_label, seat_number in positions:
        free_rows[row_label].remove(seat_number)
    return len(positions)


async def _ensure_occupancy(
    conn: AsyncConnection,
    seeded: tuple[_SeededShowtime, ...],
    guests: tuple[int, ...],
    now: datetime,
) -> tuple[_StepCounts, int, int]:
    """Book the planned share of every showtime that has no reservations yet.

    A showtime that already holds at least one reservation -- from an earlier
    run of this command or from a person using the application -- is left
    completely alone, so a re-run neither books more seats nor touches a real
    customer's booking (FR-3).

    Args:
        conn: An open connection; the caller owns the transaction.
        seeded: Every showtime of the window, in day, screen, slot order.
        guests: The guest account ids to book with.
        now: The current instant passed to the services.

    Returns:
        tuple[_StepCounts, int, int]: How many showtimes were booked and skipped,
        how many reservations were created, and how many seats they hold.
    """
    booked_ids = {
        row[0]
        for row in (
            await conn.execute(select(reservations.c.showtime_id).distinct())
        ).all()
    }
    rng = random.Random(_RANDOM_SEED)
    booked = 0
    reservations_created = 0
    seats_taken = 0
    for showtime in seeded:
        if showtime.id in booked_ids:
            continue
        seat_map = await get_seat_map(conn, showtime.id, now)
        free_rows, seat_ids = _free_seats(seat_map)
        remaining = _occupancy_target(rng, len(seat_map.seats), showtime.slot_index)
        while remaining > 0:
            taken = await _book_group(
                conn, showtime.id, free_rows, seat_ids, guests, rng, now
            )
            if taken == 0:
                break
            reservations_created += 1
            seats_taken += taken
            remaining -= taken
        booked += 1
    return (
        _StepCounts(booked, len(seeded) - booked),
        reservations_created,
        seats_taken,
    )


# --- Step 4: the demo account's own history (SPEC-7A D7) -------------------


async def _ensure_demo_reservations(
    conn: AsyncConnection,
    seeded: tuple[_SeededShowtime, ...],
    demo_user_id: int,
    now: datetime,
) -> tuple[int, int]:
    """Give the demo account two confirmed reservations and one cancelled one.

    The reservations are made through :func:`hold`, :func:`confirm` and
    :func:`cancel`, so the demo account sees exactly the states a real customer
    can produce. They are created only when the account has no reservation at
    all, so an account someone has already used keeps its own history (FR-3).

    Each reservation is placed near a fixed fraction of the window (a quarter,
    half and three quarters of the way through it) and then, if that showtime is
    too full, at the next showtime that still has two free adjacent seats. Every
    chosen showtime must be future, because only future showtimes are seeded.

    Args:
        conn: An open connection; the caller owns the transaction.
        seeded: Every showtime of the window, in day, screen, slot order.
        demo_user_id: The demo account's id.
        now: The current instant passed to the services.

    Returns:
        tuple[int, int]: How many reservations were created, and how many were
        skipped because the account already had some.

    Raises:
        SeedDemoRefusedError: If the window has no showtime, or not enough
            showtimes with two free adjacent seats, to place all three.
    """
    existing = (
        await conn.execute(
            select(func.count())
            .select_from(reservations)
            .where(reservations.c.user_id == demo_user_id)
        )
    ).scalar_one()
    if existing:
        return 0, len(_DEMO_RESERVATIONS)

    if not seeded:
        raise SeedDemoRefusedError(
            "cannot create the demo reservations: the window has no future "
            "showtime. Run the command earlier in the day."
        )

    rng = random.Random(_RANDOM_SEED + 1)
    created = 0
    used: set[int] = set()
    for index, cancelled in enumerate(_DEMO_RESERVATIONS):
        target = len(seeded) * (index + 1) // (len(_DEMO_RESERVATIONS) + 1)
        showtime_id: int | None = None
        seat_selection: list[int] | None = None
        for step in range(len(seeded)):
            candidate = seeded[(target + step) % len(seeded)]
            if candidate.id in used:
                continue
            seat_map = await get_seat_map(conn, candidate.id, now)
            free_rows, seat_ids = _free_seats(seat_map)
            positions = _find_run(free_rows, _DEMO_SEATS_PER_RESERVATION, rng)
            if positions is None:
                continue
            showtime_id = candidate.id
            seat_selection = [seat_ids[position] for position in positions]
            break
        if showtime_id is None or seat_selection is None:
            raise SeedDemoRefusedError(
                "cannot create the demo reservations: no showtime in the "
                f"{len(seeded)}-showtime window has two free adjacent seats. "
                "Delete the demo account and run the command on a fresh database."
            )
        used.add(showtime_id)
        reservation = await hold(conn, demo_user_id, showtime_id, seat_selection, now)
        confirmed = await confirm(conn, demo_user_id, reservation.id, now)
        if cancelled:
            await cancel(conn, demo_user_id, confirmed.id, now)
        created += 1
    return created, 0


# --- The command ----------------------------------------------------------


async def seed_demo(
    conn: AsyncConnection,
    settings: DemoSeedSettings,
    now: datetime,
    *,
    days: int = _WINDOW_DAYS,
) -> SeedSummary:
    """Seed the whole showcase dataset inside the caller's transaction.

    The steps run in dependency order: the accounts first (the catalog's audit
    columns need a creator), then genres, films, screens and showtimes, then the
    occupancy that needs both the showtimes and the guests, and finally the demo
    account's own reservations. Every step is idempotent, so this function may be
    called against a database it has already filled.

    Nothing is committed here: the caller owns the transaction and must commit,
    so a failure half-way leaves the database exactly as it was (matching
    :func:`src.db.seed.seed_database`).

    Args:
        conn: An open :class:`~sqlalchemy.ext.asyncio.AsyncConnection`.
        settings: The validated settings from :func:`_load_demo_seed_settings`.
        now: The current instant. Passed in rather than read here so tests can
            fix the clock and get a reproducible window.
        days: How many local calendar days, starting on the cinema's current
            day, the showtime window covers. Defaults to :data:`_WINDOW_DAYS`,
            the fortnight the command seeds; the integration tests pass ``2`` so
            they do not book a fortnight of showtimes. It must be positive.

    Returns:
        SeedSummary: What this run created and skipped, step by step.

    Raises:
        ValueError: If ``days`` is not positive.
        SeedDemoRefusedError: If the window has no future showtime, or a demo
            reservation cannot be seated.
    """
    if days < 1:
        raise ValueError("days must be at least 1")
    zone = ZoneInfo(settings.cinema_timezone)
    today = now.astimezone(zone).date()

    demo_user_created, demo_user_id = await _ensure_demo_user(
        conn, settings.demo_user_email, settings.demo_user_password
    )
    admin_id = await _find_admin_id(conn)
    actor_id = demo_user_id if admin_id is None else admin_id

    genre_counts, genre_ids = await _ensure_genres(conn, actor_id)
    movie_counts, movie_ids = await _ensure_movies(
        conn, genre_ids, actor_id, settings.poster_base_url
    )
    screen_counts, screens = await _ensure_screens(conn, actor_id)
    showtime_counts, seeded, started = await _ensure_showtimes(
        conn, movie_ids, screens, actor_id, zone, today, now, days=days
    )
    guest_counts, guests = await _ensure_guests(conn)
    occupancy_counts, reservations_created, seats_taken = await _ensure_occupancy(
        conn, seeded, guests, now
    )
    demo_created, demo_skipped = await _ensure_demo_reservations(
        conn, seeded, demo_user_id, now
    )

    return SeedSummary(
        genres_created=genre_counts.created,
        genres_skipped=genre_counts.skipped,
        movies_created=movie_counts.created,
        movies_skipped=movie_counts.skipped,
        screens_created=screen_counts.created,
        screens_skipped=screen_counts.skipped,
        showtimes_created=showtime_counts.created,
        showtimes_skipped=showtime_counts.skipped,
        showtimes_past_skipped=started,
        guests_created=guest_counts.created,
        guests_skipped=guest_counts.skipped,
        showtimes_booked=occupancy_counts.created,
        showtimes_already_booked=occupancy_counts.skipped,
        guest_reservations_created=reservations_created,
        seats_taken=seats_taken,
        demo_user_created=demo_user_created,
        demo_reservations_created=demo_created,
        demo_reservations_skipped=demo_skipped,
    )


def _line(label: str, created: int, skipped: int, noun: str) -> str:
    """Format one summary line the same way for every step."""
    return f"  {label:<12}{created:>4} {noun} created, {skipped:>4} already present"


def format_summary(summary: SeedSummary) -> str:
    """Render a run's :class:`SeedSummary` as the text the command prints.

    Args:
        summary: The counts returned by :func:`seed_demo`.

    Returns:
        str: A short report, one line per dataset, without a trailing newline.
    """
    lines = [
        "Showcase data ready.",
        _line("genres", summary.genres_created, summary.genres_skipped, "genre(s)"),
        _line("films", summary.movies_created, summary.movies_skipped, "film(s)"),
        _line("screens", summary.screens_created, summary.screens_skipped, "screen(s)"),
        _line(
            "showtimes",
            summary.showtimes_created,
            summary.showtimes_skipped,
            "showtime(s)",
        ),
        _line("guests", summary.guests_created, summary.guests_skipped, "guest(s)"),
        _line(
            "seat maps",
            summary.showtimes_booked,
            summary.showtimes_already_booked,
            "showtime(s) booked",
        ),
        f"  {summary.guest_reservations_created} guest reservation(s) confirmed, "
        f"{summary.seats_taken} seat(s) taken",
    ]
    if summary.demo_user_created:
        lines.append("  demo account created")
    else:
        lines.append("  demo account already existed")
    lines.append(
        f"  {summary.demo_reservations_created} demo reservation(s) created, "
        f"{summary.demo_reservations_skipped} already present"
    )
    if summary.showtimes_past_skipped:
        lines.append(
            f"  {summary.showtimes_past_skipped} slot(s) of today had already "
            f"started and were skipped"
        )
    return "\n".join(lines)


async def run_demo_seed() -> SeedSummary:
    """CLI entry point: load settings, seed inside one transaction, commit.

    Delegates all work to :func:`seed_demo` and lets :func:`_load_demo_seed_settings`
    refuse a misconfigured target before any connection is opened. If anything
    raises, the transaction is rolled back and the database is left untouched.

    Side effects: opens and commits one database transaction, and disposes the
    process-wide async engine (``src.db.engine.engine``) before returning so a
    short-lived CLI process exits without leaving pooled connections open.

    Returns:
        SeedSummary: What this run created and skipped.

    Raises:
        SeedDemoRefusedError: If a credential is missing, the target is a test
            database, or the slot separation is wider than the seeded slots.
    """
    settings = _load_demo_seed_settings()
    try:
        async with engine.begin() as conn:
            return await seed_demo(conn, settings, datetime.now(UTC))
    finally:
        await engine.dispose()


async def _run_and_report() -> int:
    """Run the seed, print its report, and turn a refusal into exit code 1.

    Returns:
        int: ``0`` when the showcase data is in place, ``1`` when the command
        refused to run.
    """
    try:
        summary = await run_demo_seed()
    except SeedDemoRefusedError as refusal:
        print(f"seed_demo: {refusal}", file=sys.stderr)
        return 1
    print(format_summary(summary))
    return 0


def main() -> int:
    """Run the command on a fresh event loop and return its exit code.

    Returns:
        int: ``0`` when the showcase data is in place, ``1`` when the command
        refused to run. An unexpected error is not caught, so it keeps its
        traceback.
    """
    return asyncio.run(_run_and_report())


if __name__ == "__main__":
    if sys.platform == "win32":
        # Python on Windows defaults to the ProactorEventLoop, but async psycopg
        # refuses to run on it ("Psycopg cannot use the 'ProactorEventLoop' to
        # run in async mode"); it needs a SelectorEventLoop instead.
        raise SystemExit(
            asyncio.run(_run_and_report(), loop_factory=asyncio.SelectorEventLoop)
        )
    raise SystemExit(main())
