@dataclass(frozen=True, slots=True)
class _SeededShowtime:
    """One showtime of the window, with the coordinates that chose it.

    Attributes:
        id: The showtime's primary key.
        day_offset: Days after the first day of the window.
        screen_index: Position of its screen in :data:`_SCREEN_SPECS`.
        slot_index: Position of its slot in :data:`_SLOTS`.
    """

    id: int
    day_offset: int
    screen_index: int
    slot_index: int


async def _ensure_showtimes(
    conn: AsyncConnection,
    movie_ids: dict[str, int],
    screens: tuple[ScreenRecord, ...],
    actor_id: int,
    zone: ZoneInfo,
    today: date,
    now: datetime,
    *,
    days: int,
) -> tuple[_StepCounts, tuple[_SeededShowtime, ...], int]:
    """Create the window's showtimes, skipping existing screens and instants.

    Args:
        conn: An open connection; the caller owns the transaction.
        movie_ids: The film ids produced by :func:`_ensure_movies`.
        screens: The showcase screens, in :data:`_SCREEN_SPECS` order.
        actor_id: The user recorded as the creator of a new showtime.
        zone: The cinema's timezone.
        today: The cinema-local calendar day the window starts on.
        now: The current instant; slots that have already started are skipped.
        days: How many local calendar days the window covers, starting on
            ``today``; the command passes :data:`_WINDOW_DAYS`.

    Returns:
        tuple[_StepCounts, tuple[_SeededShowtime, ...], int]: How many showtimes
        were created and already existed, every showtime of the window in day,
        screen, slot order, and how many slots were skipped as already started.
    """
    rows = (
        await conn.execute(
            select(showtimes.c.id, showtimes.c.screen_id, showtimes.c.starts_at)
        )
    ).all()
    ids_by_key = {
        (screen_id, _as_utc(starts_at)): showtime_id
        for showtime_id, screen_id, starts_at in rows
    }

    created = 0
    started = 0
    seeded: list[_SeededShowtime] = []
    for day_offset in range(days):
        for screen_index, screen in enumerate(screens):
            for slot_index, (hour, _) in enumerate(_SLOTS):
                starts_at = _showtime_instant(zone, today, day_offset, hour)
                if starts_at <= now:
                    started += 1
                    continue
                key = (screen.id, starts_at)
                showtime_id = ids_by_key.get(key)
                if showtime_id is None:
                    film = _FILMS[_movie_index(day_offset, screen_index, slot_index)]
                    record = await create_showtime(
                        conn,
                        ShowtimeCreate(
                            movie_id=movie_ids[film.title],
                            screen_id=screen.id,
                            starts_at=starts_at,
                            price_cents=_price_cents(screen_index, slot_index),
                        ),
                        actor_id,
                        now,
                    )
                    showtime_id = record.id
                    ids_by_key[key] = showtime_id
                    created += 1
                seeded.append(
                    _SeededShowtime(
                        id=showtime_id,
                        day_offset=day_offset,
                        screen_index=screen_index,
                        slot_index=slot_index,
                    )
                )
    return _StepCounts(created, len(seeded) - created), tuple(seeded), started


