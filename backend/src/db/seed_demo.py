# --- Pure arithmetic and planning helpers ---------------------------------


def _as_utc(value: datetime) -> datetime:
    """Return ``value`` as an aware UTC instant.

    PostgreSQL returns ``timestamptz`` columns as aware datetimes, but a driver
    or a test double may hand back a naive one; normalising here keeps the
    screen/instant lookup keys comparable.

    Args:
        value: The stored start instant.

    Returns:
        datetime: The same instant in UTC.
    """
    return value.replace(tzinfo=UTC) if value.tzinfo is None else value.astimezone(UTC)


def _showtime_instant(
    zone: ZoneInfo, today: date, day_offset: int, hour: int
) -> datetime:
    """Return local ``hour`` on ``today + day_offset`` as a UTC instant.

    Args:
        zone: The cinema's timezone (``CINEMA_TIMEZONE``).
        today: The cinema-local calendar day the window starts on.
        day_offset: Days after ``today``.
        hour: The local hour of the slot, e.g. ``18``.

    Returns:
        datetime: The start instant in UTC, as SPEC-3 requires.
    """
    local = datetime.combine(
        today + timedelta(days=day_offset), time(hour), tzinfo=zone
    )
    return local.astimezone(UTC)


def _movie_index(day_offset: int, screen_index: int, slot_index: int) -> int:
    """Return the catalog position of the film at one slot (SPEC-7A FR-4).

    A pure function of the slot's coordinates, so every film is shown and the
    same slot always shows the same film. The multipliers are coprime with the
    twelve-film catalog, so the three coordinates reach every position.

    Args:
        day_offset: Days after the first day of the window.
        screen_index: Position of the screen in :data:`_SCREEN_SPECS`.
        slot_index: Position of the slot in :data:`_SLOTS`.

    Returns:
        int: An index into :data:`_FILMS`.
    """
    return (day_offset * 5 + screen_index * 3 + slot_index * 2) % len(_FILMS)


def _price_cents(screen_index: int, slot_index: int) -> int:
    """Return the ticket price of one slot in integer cents (SPEC-7A D5).

    Args:
        screen_index: Position of the screen in :data:`_SCREEN_SPECS`.
        slot_index: Position of the slot in :data:`_SLOTS`.

    Returns:
        int: The slot's base price, plus the surcharge for the third screen.
    """
    base = _SLOTS[slot_index][1]
    if screen_index == _SURCHARGE_SCREEN_INDEX:
        return base + _SCREEN_SURCHARGE_CENTS
    return base


def _occupancy_target(rng: random.Random, seat_count: int, slot_index: int) -> int:
    """Return how many seats of one showtime to book (SPEC-7A D6).

    The share is drawn from a band of the slot's target share plus or minus
    :data:`_OCCUPANCY_JITTER`, and the result is rounded *up*: a seat count is
    never booked below the floor of that band, so every showtime really sits
    inside D6's plus or minus ten points once the seats are in.

    Args:
        rng: The seeded generator, consumed here so the plan is reproducible.
        seat_count: Number of seats on the showtime's screen.
        slot_index: Position of the slot; later slots are busier.

    Returns:
        int: A target between one seat and one seat short of a full house, so
        every seat map keeps at least one free seat to click.
    """
    jitter = rng.uniform(-_OCCUPANCY_JITTER, _OCCUPANCY_JITTER)
    share = _OCCUPANCY_SHARES[slot_index] + jitter
    target = math.ceil(seat_count * share)
    return max(1, min(target, seat_count - 1))


def _pick_group_size(rng: random.Random) -> int:
    """Return the size of the next booking group, one to four seats (D6)."""
    return rng.choices(_GROUP_SIZES, weights=_GROUP_WEIGHTS, k=1)[0]


def _find_run(
    free_rows: dict[str, list[int]], size: int, rng: random.Random
) -> list[tuple[str, int]] | None:
    """Pick ``size`` adjacent free seats in one row, or ``None``.

    Args:
        free_rows: Free seat numbers per row label, each list ascending. The
            function does not mutate it.
        size: How many adjacent seats are wanted.
        rng: The seeded generator; one draw picks among all candidate runs.

    Returns:
        list[tuple[str, int]] | None: ``(row_label, seat_number)`` positions in
        ascending seat order, or ``None`` when no row has such a run.
    """
    runs: list[list[tuple[str, int]]] = []
    for row_label in sorted(free_rows):
        numbers = free_rows[row_label]
        start = 0
        while start < len(numbers):
            end = start
            while end + 1 < len(numbers) and numbers[end + 1] == numbers[end] + 1:
                end += 1
            for offset in range(start, end - size + 2):
                runs.append(
                    [(row_label, number) for number in numbers[offset : offset + size]]
                )
            start = end + 1
    if not runs:
        return None
    return rng.choice(runs)


def _free_seats(
    seat_map: SeatMapOut,
) -> tuple[dict[str, list[int]], dict[tuple[str, int], int]]:
    """Split a seat map into its free positions and their seat ids.

    Args:
        seat_map: The public seat map of one showtime.

    Returns:
        tuple[dict[str, list[int]], dict[tuple[str, int], int]]: The free seat
        numbers per row label, ascending, and a lookup from
        ``(row_label, seat_number)`` to the seat's primary key.
    """
    free_rows: dict[str, list[int]] = {}
    seat_ids: dict[tuple[str, int], int] = {}
    for seat in seat_map.seats:
        if seat.state != "available":
            continue
        free_rows.setdefault(seat.row_label, []).append(seat.seat_number)
        seat_ids[(seat.row_label, seat.seat_number)] = seat.seat_id
    for numbers in free_rows.values():
        numbers.sort()
    return free_rows, seat_ids


