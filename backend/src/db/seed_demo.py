"""Showcase demo data for the Movie Reservation System (SPEC-7A).

``python -m src.db.seed_demo`` fills a development database with believable
fictional content for the next fourteen days: the six genres and twelve films of
SPEC-7A Section 2.2 (each with an original poster generated by
``tools/generate_posters.py``), three screens, four showtimes per screen per day,
partly booked seat maps and a demo account with three reservations. The data is
optional: the application never runs this command and never depends on it
(SPEC-7A D1). The window length is a keyword argument of :func:`seed_demo`
(:data:`_WINDOW_DAYS` by default), so the integration tests seed only two days.

Usage (from ``backend/`` with the virtual environment active)::

    python -m src.db.seed_demo

The command reads ``DEMO_USER_EMAIL``, ``DEMO_USER_PASSWORD`` and
``DEMO_POSTER_BASE_URL`` from the environment or ``backend/.env`` through
:class:`_DemoSettings`, the same way :mod:`src.db.seed` reads its credentials.
Only ``DEMO_POSTER_BASE_URL`` has a default; there is no default password
(SPEC-7A D7, IMPLEMENTER RULES rule 6).

Guards (SPEC-7A FR-5): the command stops with a clear message and a non-zero
exit code, before opening a connection, when either credential is missing or
when the configured database name ends with ``_test``.

Every write goes through the existing service functions -- ``create_genre``,
``create_movie``, ``create_screen``, ``create_showtime``, ``auth.signup``,
``reservations.hold``, ``confirm`` and ``cancel`` -- so the overlap rule, the
partial unique index on active seats and the money rules all hold (FR-2). The
services never commit; this command owns the transaction, exactly as
:mod:`src.db.seed` does.

Idempotency (FR-3): every step looks for its data first (a genre by name, a film
by title, a screen by name, a showtime by screen and instant, a showtime that
already has reservations, the demo account by email, the demo account that
already has reservations) and does nothing when it finds it. A second run
therefore adds no row. Determinism (FR-4): the occupancy plan uses one
:class:`random.Random` seeded with :data:`_RANDOM_SEED`, consumed in the fixed
order of day, screen and slot, so a fresh run always books the same seats.

Runtime: the occupancy step books about seven thousand seats in groups of one to
four through the real services, which costs roughly fifteen round trips per
group. On a local PostgreSQL that is a minute or two; against a database on the
far side of a wide-area network it is tens of minutes, because every service call
is a network round trip.

A note on runtime minutes: SPEC-7A Section 2.2 lists a runtime for every film,
but the ``movies`` table (SPEC-1 Section 2.3) has no runtime column and SPEC-7A
promises no schema change, so the runtime lives only in
``tools/generate_posters.py`` and is not stored by this command.
"""

