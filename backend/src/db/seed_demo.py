# --- Settings and the SPEC-7A FR-5 guard -----------------------------------


class SeedDemoRefusedError(RuntimeError):
    """The command refused to run; nothing was written.

    A dedicated exception (rather than a bare :class:`RuntimeError`) lets
    ``main`` tell a refusal apart from an unexpected programming error, which it
    reports with a different message and a different exit code.
    """


class _DemoSettings(BaseSettings):
    """The showcase-specific settings, read from the environment or ``.env``.

    The names are upper-cased aliases because that is how they appear in
    ``backend/.env``, mirroring how :mod:`src.db.seed` reads ``SEED_ADMIN_*``.
    Blank values are normalised to ``None`` so the guard can report them as
    missing rather than as an empty string.
    """

    model_config = SettingsConfigDict(
        env_file=".env", env_file_encoding="utf-8", extra="ignore"
    )

    demo_user_email: str | None = Field(default=None, alias="DEMO_USER_EMAIL")
    demo_user_password: str | None = Field(default=None, alias="DEMO_USER_PASSWORD")
    demo_poster_base_url: str = Field(
        default=_DEFAULT_POSTER_BASE_URL, alias="DEMO_POSTER_BASE_URL"
    )

    @field_validator("demo_user_email", "demo_user_password", mode="before")
    @classmethod
    def _strip_or_none(cls, value: object) -> object:
        """Return ``None`` for an absent or blank value, else the stripped text."""
        if isinstance(value, str):
            stripped = value.strip()
            return stripped or None
        return value

    @field_validator("demo_poster_base_url", mode="before")
    @classmethod
    def _strip_base_url(cls, value: object) -> object:
        """Strip surrounding whitespace and trailing slashes from the URL."""
        if isinstance(value, str):
            return value.strip().rstrip("/")
        return value


@dataclass(frozen=True, slots=True)
class DemoSeedSettings:
    """The validated inputs ``seed_demo`` needs; no defaults, no session state.

    Attributes:
        demo_user_email: The demo account's e-mail address, used as its login.
        demo_user_password: The demo account's plain-text password, hashed by
            :func:`src.auth.service.signup` and never stored by this command.
        poster_base_url: Absolute prefix for poster URLs, without a trailing
            slash; the file name is appended as ``/posters/<slug>.svg``.
        cinema_timezone: IANA zone name for "local noon", read from the
            application settings so the window matches the catalog's rules.
    """

    demo_user_email: str
    demo_user_password: str
    poster_base_url: str
    cinema_timezone: str


def validate_demo_seed_target(
    *,
    database_url: str,
    demo_user_email: str | None,
    demo_user_password: str | None,
    showtime_slot_minutes: int,
) -> None:
    """Enforce SPEC-7A FR-5 before anything is written.

    Args:
        database_url: The configured SQLAlchemy URL of the target database.
        demo_user_email: ``DEMO_USER_EMAIL``, or ``None`` when it is unset.
        demo_user_password: ``DEMO_USER_PASSWORD``, or ``None`` when it is unset.
        showtime_slot_minutes: ``SHOWTIME_SLOT_MINUTES``, the minimum separation
            the catalog enforces between two showtimes on one screen.

    Raises:
        SeedDemoRefusedError: If a credential is missing, if the database name ends
            with ``_test``, or if the configured slot separation is wider than
            the four fixed slots this command creates. The message names the
            offending setting and says what to do about it, because the command
            is aimed at people running it for the first time.
    """
    missing = [
        name
        for name, value in (
            ("DEMO_USER_EMAIL", demo_user_email),
            ("DEMO_USER_PASSWORD", demo_user_password),
        )
        if value is None
    ]
    if missing:
        raise SeedDemoRefusedError(
            "refusing to seed showcase data: "
            + ", ".join(missing)
            + " is not set. Add it to backend/.env (see .env.example) and try "
            "again; there is no default demo password."
        )

    database_name = make_url(database_url).database or ""
    if database_name.endswith(_TEST_DATABASE_SUFFIX):
        raise SeedDemoRefusedError(
            f"refusing to seed showcase data: the configured database "
            f"{database_name!r} is a test database. Point DATABASE_URL at a "
            f"development database instead."
        )

    if showtime_slot_minutes > _SLOT_SEPARATION_MINUTES:
        raise SeedDemoRefusedError(
            f"refusing to seed showcase data: SHOWTIME_SLOT_MINUTES is "
            f"{showtime_slot_minutes}, but the four daily slots are "
            f"{_SLOT_SEPARATION_MINUTES} minutes apart, so the catalog's overlap "
            f"rule would reject them. Lower SHOWTIME_SLOT_MINUTES to "
            f"{_SLOT_SEPARATION_MINUTES} or less and try again."
        )


def _load_demo_seed_settings() -> DemoSeedSettings:
    """Build validated settings from the environment and application config.

    Returns:
        The settings :func:`seed_demo` needs.

    Raises:
        SeedDemoRefusedError: If a required credential is missing.
    """
    demo = _DemoSettings()
    app = get_settings()
    validate_demo_seed_target(
        database_url=app.database_url,
        demo_user_email=demo.demo_user_email,
        demo_user_password=demo.demo_user_password,
        showtime_slot_minutes=app.showtime_slot_minutes,
    )
    email = demo.demo_user_email
    password = demo.demo_user_password
    if email is None or password is None:  # pragma: no cover - guard above
        raise SeedDemoRefusedError(
            "refusing to seed showcase data: credentials missing"
        )
    return DemoSeedSettings(
        demo_user_email=email,
        demo_user_password=password,
        poster_base_url=demo.demo_poster_base_url or _DEFAULT_POSTER_BASE_URL,
        cinema_timezone=app.cinema_timezone,
    )


# --- Poster URLs ----------------------------------------------------------


def slugify(title: str) -> str:
    """Turn a film title into its poster's file name.

    This is the same rule ``tools/generate_posters.py`` uses to name the SVG
    files, restated here because the tool is not importable from the backend
    package. ``test_seed_demo.py`` compares both name lists, so the two copies
    cannot drift apart unnoticed.

    Args:
        title: The film title, in any case.

    Returns:
        str: The lowercased title with every run of non-alphanumeric characters
        collapsed into a single hyphen and no leading or trailing hyphen, so
        ``"A Year in Tbilisi Rain"`` becomes ``"a-year-in-tbilisi-rain"``.
    """
    slug = "".join(character if character.isalnum() else "-" for character in title)
    return "-".join(part for part in slug.lower().split("-") if part)


def poster_url(base_url: str, title: str) -> str:
    """Build a film's absolute poster URL from the configured base URL.

    SPEC-3 requires ``poster_url`` to be an absolute ``http(s)`` URL, so the
    relative file path under ``frontend/public`` is prefixed with
    ``DEMO_POSTER_BASE_URL`` (the Vite development server by default).

    Args:
        base_url: The origin serving the frontend, without a trailing slash.
        title: The film title; its slug names the file.

    Returns:
        str: ``<base_url>/posters/<slug>.svg``.
    """
    return f"{base_url}{_POSTER_DIRECTORY}/{slugify(title)}.svg"


